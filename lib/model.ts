// Token Radar — the value model (radar-2).
//
// One sealed snapshot in, one ranked board out. The board covers every slug on the
// snapshot's watchlist (the floor, never the ceiling) plus every other rankable
// pre-token protocol below the floor, by TVL. A protocol is pre-token when its
// record carries no token (no market cap, no CoinGecko id, no symbol); protocols
// whose token already trades are kept apart in the Live view, at the market's own
// values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. For one protocol:
//
//   base        = tvl_usd x BASE_MULTIPLE
//   growth      = clamp(change_7d, GROWTH_FLOOR, GROWTH_CAP) per cent
//   growthMult  = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity    = MATURITY_FLOOR + min(age_days, MATURITY_DAYS) / MATURITY_DAYS x MATURITY_RANGE
//                 (age_days unknown: UNKNOWN_AGE_DAYS)
//   precedent   = PRECEDENT_FLOOR + launchRate(category) x PRECEDENT_RANGE
//                 launchRate(category) is the share of the snapshot's protocols in
//                 that category that already record a token, read off the snapshot
//                 itself (categories with fewer than MIN_CATEGORY_N protocols, and
//                 protocols with no category, use the snapshot's global rate).
//                 A category whose peers have mostly launched is a category the
//                 market has already shown it will tokenize.
//   reach       = 1 + REACH_PER_CHAIN x min(chains.length, REACH_MAX_CHAINS)
//   implied     = max(1, round(base x growthMult x maturityMult x precedentMult x reachMult))
//
// No protocol name is ever special-cased: the same function scores every row.
// The constants are stated in the dashboard's methodology section, so the judge
// can read the model off the page as well as off this file.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
